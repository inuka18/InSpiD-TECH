export function getPhasesForProject(projectId) {
  return mockSchedulePhases.find((p) => p.projectId === projectId)?.phases ?? [];
}

export function getAllTasksForProject(projectId) {
  return getPhasesForProject(projectId).flatMap((phase) =>
    phase.tasks.map((task) => ({ ...task, phaseId: phase.id, phaseName: phase.name }))
  );
}

export function getScheduleTaskById(projectId, taskId) {
  return getAllTasksForProject(projectId).find((t) => t.id === taskId) ?? null;
}

// Appends a brand-new task straight into the real phases array (the
// Kanban Board's "+ Add Task" creates here), dropped into whichever
// phase's date window currently contains TODAY, or the last phase if
// none does, since a newly created task has no phase concept of its own
// on the board. Returns the same object reference that was pushed, so
// the caller can immediately reference it (e.g. to open its detail view)
// without a re-fetch.
export function addTaskToProject(projectId, task) {
  const projectEntry = mockSchedulePhases.find((p) => p.projectId === projectId);
  if (!projectEntry) return null;
  const phases = projectEntry.phases;
  if (phases.length === 0) return null;
  const activePhase =
    phases.find((phase) => new Date(phase.start) <= TODAY && TODAY <= new Date(phase.end)) ?? phases[phases.length - 1];
  activePhase.tasks.push(task);
  return task;
}
